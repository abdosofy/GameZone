// اسم المفتاح الموحد لتخزين الألعاب
const GAMES_STORAGE_KEY = "gameZoneGames";

// قراءة الألعاب من المتصفح
export const getGames = () => {
  try {
    const savedGames = localStorage.getItem(GAMES_STORAGE_KEY);

    if (savedGames === null) {
      return defaultGames;
    }

    const parsedGames = JSON.parse(savedGames);

    return Array.isArray(parsedGames) ? parsedGames : defaultGames;
  } catch {
    return defaultGames;
  }
};

// حفظ الألعاب بعد الإضافة أو التعديل أو الحذف
export const saveGames = (games) => {
  localStorage.setItem(GAMES_STORAGE_KEY, JSON.stringify(games));

  window.dispatchEvent(new Event("gamesUpdated"));
};